const norm = value => String(value||'').trim().toLocaleLowerCase();
function randomize(list,random=Math.random){
  const a=[...list];for(let i=a.length-1;i>0;i--){
    const j=Math.floor(random()*(i+1));[a[i],a[j]]=[a[j],a[i]];
  }
  return a;
}
function escapeRegExp(value){return value.replace(/[.*+?^$\{\}()|[\]\\]/g,'\\$&')}
function gapFor(text,expression){
  if(!text||!expression)return null;
  const re=new RegExp('(^|[^A-Za-zÀ-ÖØ-öø-ÿ])('+escapeRegExp(expression)+')(?=$|[^A-Za-zÀ-ÖØ-öø-ÿ])','i');
  const m=re.exec(text);
  if(!m)return null;
  const start=m.index+m[1].length;
  return {before:text.slice(0,start),after:text.slice(start+m[2].length),answer:m[2]};
}
export function createWordExercise(cards,pool,random=Math.random){
  const candidates=pool.filter(card=>card&&!card.deletedAt&&card.en);
  const fullList=cards.filter(card=>card&&!card.deletedAt&&card.en);
  const usable=candidates.map(card=>{
    const key=norm(card.en),bank=CONTEXT_BANK[key];
    const contexts=[];
    // The English tutor may save additional reviewed examples per card.
    for(const item of Array.isArray(card.exerciseExamples)?card.exerciseExamples:[]){
      if(!item||typeof item.en!=='string')continue;
      const gap=gapFor(item.en,card.en);
      if(gap)contexts.push({...gap,text:item.en,translation:String(item.ru||''),origin:'tutor'});
    }
    if(bank){const gap=gapFor(bank[0][0],card.en);if(gap)contexts.push({...gap,text:bank[0][0],translation:bank[0][1],origin:'prepared'})}
    if(card.example){const gap=gapFor(card.example,card.en);if(gap)contexts.push({...gap,text:card.example,translation:card.exampleRu||'',origin:'saved'})}
    return {card,contexts,group:bank?.[1]||'other'};
  }).filter(x=>x.contexts.length);
  if(!usable.length)return {items:[],unavailable:candidates.length};
  const shuffled=randomize(usable,random);
  const items=[],previous=new Map();
  for(let i=0;i<10;i++){
    const item=shuffled[i%shuffled.length],visit=previous.get(item.card.id)||0;
    previous.set(item.card.id,visit+1);
    const context=item.contexts[visit%item.contexts.length];
    const sameGroup=fullList.filter(c=>c.id!==item.card.id&&CONTEXT_BANK[norm(c.en)]?.[1]===item.group);
    const allOthers=fullList.filter(c=>c.id!==item.card.id);
    const distractors=[...randomize(sameGroup,random),...randomize(allOthers.filter(c=>!sameGroup.some(z=>z.id===c.id)),random)]
      .filter((c,i,arr)=>arr.findIndex(x=>norm(x.en)===norm(c.en))===i)
      .slice(0,3).map(c=>c.en);
    const extra=Object.entries(CONTEXT_BANK)
      .filter(([key,val])=>key!==norm(item.card.en)&&val[1]===item.group)
      .map(([key])=>key);
    const allFallback=Object.keys(CONTEXT_BANK).filter(key=>key!==norm(item.card.en));
    const filled=[...distractors];
    for(const alternative of [...randomize(extra,random),...randomize(allFallback,random)]){
      if(filled.length>=3)break;
      if(alternative!==norm(item.card.en)&&!filled.some(x=>norm(x)===alternative))filled.push(alternative);
    }
    const options=randomize([item.card.en,...filled],random);
    items.push({id:item.card.id+'-'+i,cardId:item.card.id,expression:item.card.en,
      translation:context.translation,before:context.before,after:context.after,
      sentence:context.text,options,correctIndex:options.findIndex(x=>norm(x)===norm(item.card.en)),
      source:context.origin});
  }
  return {items,unavailable:candidates.length-usable.length};
}
